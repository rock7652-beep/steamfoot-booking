import DashboardLayout from "@/components/dashboard-layout";
const user = { id: "owner", role: "OWNER", staffId: "staff", storeId: "own" };
beforeEach(() => {
  vi.clearAllMocks();
  mocks.user.mockResolvedValue(user);
  mocks.permissions.mockResolvedValue([]);
  mocks.options.mockResolvedValue([]);
  mocks.ownStore.mockResolvedValue({slug: "own-store"});
  mocks.active.mockRejectedValue(new AppError("FORBIDDEN", "private requested-store metadata"));
});
it.each(["FORBIDDEN", "NOT_FOUND"] as const)("renders safe recovery for %s before any scoped reads", async code => {
  mocks.active.mockRejectedValue(new AppError(code, "private requested-store metadata"));
  const html = renderToStaticMarkup(await DashboardLayout({children: React.createElement("p", null, "private dashboard content")}));
  expect(html).toContain("無法存取此店舖");
  expect(html).toContain('href="/s/own-store/admin/dashboard"');
  expect(html).not.toContain("private");
  expect(mocks.audit).not.toHaveBeenCalled();
  expect(mocks.options).not.toHaveBeenCalled();
  expect(mocks.permissions).not.toHaveBeenCalled();
  expect(mocks.ownStore).toHaveBeenCalledWith(expect.objectContaining({where: expect.objectContaining({id: "own"})}));
});
it("offers sign-in when the own store is unavailable", async () => {
  mocks.ownStore.mockResolvedValue(null);
  const html = renderToStaticMarkup(await DashboardLayout({children: null}));
  expect(html).toContain('href="/login"');
  expect(html).not.toContain('href="/dashboard"');
});
it("preserves unexpected failures instead of disguising them as permission denials", async () => {
  const failure = new Error("database disconnected");
  mocks.active.mockRejectedValue(failure);
  await expect(DashboardLayout({children: null})).rejects.toBe(failure);
  expect(mocks.ownStore).not.toHaveBeenCalled();
});
it("keeps authorized child-store reads on the normal layout path", async () => {
  mocks.active.mockResolvedValue("authorized-child");
  const reached = new Error("authorized layout continues");
  mocks.audit.mockRejectedValue(reached);
  await expect(DashboardLayout({children: null})).rejects.toBe(reached);
  expect(mocks.audit).toHaveBeenCalledWith(user);
  expect(mocks.ownStore).not.toHaveBeenCalled();
});
