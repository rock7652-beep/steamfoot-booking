export function canReviewDraftGuides() {
  return process.env.VERCEL_ENV === "preview" || (process.env.VERCEL_ENV !== "production" && ["development", "test"].includes(process.env.NODE_ENV ?? ""));
}

export function visiblePublicGuides() {
  return PUBLIC_GUIDES.filter(guide => guide.status === "published" || canReviewDraftGuides());
}

export function findPublicGuide(slug: string) {
  return visiblePublicGuides().find(guide => guide.id === slug);
}

export function guidePath(guide: Pick<PublicGuide, "id">): `/guides/${string}` {
  return `/guides/${guide.id}`;
}

export const PUBLISHED_GUIDE_PATHS = PUBLIC_GUIDES.filter(guide => guide.status === "published").map(guidePath);
