import {build} from 'esbuild';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createRequire} from 'node:module';
import postcss from 'postcss';
import tailwind from '@tailwindcss/postcss';
const require=createRequire(import.meta.url),{chromium}=require('playwright');
const out=process.env.QA_OUTPUT||'/tmp/addon-density-preview',root=process.cwd();mkdirSync(out,{recursive:true});
await build({entryPoints:['scripts/qa/addon-density-fixture.tsx'],bundle:true,format:'iife',jsx:'automatic',outfile:out+'/app.js',alias:{'@':root+'/src'},loader:{'.css':'css'}});
const css=await postcss([tailwind()]).process(readFileSync('src/app/globals.css','utf8'),{from:root+'/src/app/globals.css'});
writeFileSync(out+'/style.css',css.css);
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
const results=[];
for(const [width,height] of [[1366,900],[1920,1080],[1024,768],[768,1024],[390,844]]){
 const page=await browser.newPage({viewport:{width,height}});
 await page.route('**/*',r=>{const p=new URL(r.request().url()).pathname;return r.fulfill({contentType:p.endsWith('.js')?'text/javascript':p.endsWith('.css')?'text/css':'text/html',body:p==='/app.js'?readFileSync(out+'/app.js'):p==='/style.css'?readFileSync(out+'/style.css'):'<html><meta charset="utf-8"><link rel="stylesheet" href="/style.css"><div id="root"></div><script src="/app.js"></script></html>'});});
 await page.goto('http://fixture.local/');
 const toggle=page.getByRole('button',{name:'共同商品勾選服務項目'});
 await toggle.click();
 if(!await page.getByRole('checkbox',{name:'已下架服務（已下架）'}).isDisabled())throw Error('retired service enabled');
 await page.getByText('肩頸按摩',{exact:true}).click();
 if(!await page.getByText('· 已選 1 項',{exact:true}).isVisible())throw Error('mapping count');
 await toggle.click();await page.getByRole('button',{name:'修改瓜茶',exact:true}).click();
 await page.getByRole('textbox',{name:'商品名稱',exact:true}).fill('密度測試商品');
 await page.setViewportSize({width:width===768?1024:width,height});
 if(await page.getByRole('textbox',{name:'商品名稱',exact:true}).inputValue()!=='密度測試商品')throw Error('draft lost');
 await page.getByRole('button',{name:'修改密度測試商品',exact:true}).click();
 await page.setViewportSize({width,height});
 const check=await page.evaluate(()=>({overflow:document.documentElement.scrollWidth>innerWidth,cardWidth:document.querySelector('section[aria-label="共同商品設定"]').getBoundingClientRect().width,rowHeight:document.querySelector('button[aria-label="修改運動飲"]').getBoundingClientRect().height,selection:JSON.parse(document.querySelector('input[name="addOnGroups"]').value)[0].subjectIds}));
 if(check.overflow||check.rowHeight<44||check.selection[0]!=='massage')throw Error(JSON.stringify(check));
 await page.screenshot({path:`${out}/${width}.png`,fullPage:true});
 await toggle.click();
 await page.screenshot({path:`${out}/${width}-services.png`,fullPage:true});
 await page.getByRole('button',{name:'清除指定',exact:true}).click();
 if(!await page.getByText('· 尚未指定',{exact:true}).isVisible())throw Error('clear mapping failed');
 results.push({width,height,...check});
 await page.goto('http://fixture.local/?multiple');
 const columns=await page.locator('section[aria-label="共同商品設定"]').evaluate(el=>getComputedStyle(el.parentElement).gridTemplateColumns);
 results.at(-1).columns=columns;
 await page.close();
}
writeFileSync(out+'/results.json',JSON.stringify(results,null,2));console.log(JSON.stringify(results,null,2));await browser.close();
