// Real credentials UI -> Next Server Action -> disposable PostgreSQL -> idle observer.
import { createRequire } from "node:module";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.QA_PLAYWRIGHT_MODULE || "playwright");
const { PrismaClient } = require("@prisma/client");
const { PrismaClient: CourseClient } = require("../../generated/course-client");
const databaseUrl = "postgresql://postgres@127.0.0.1:55438/sports_live_flow_test";
if (process.env.DATABASE_URL !== databaseUrl) throw new Error("Explicit disposable DATABASE_URL required");
const db = new PrismaClient({ datasourceUrl: databaseUrl }), course = new CourseClient({ datasourceUrl: databaseUrl });
const out = path.resolve(process.env.QA_OUTPUT || "artifacts/sports-live-flow-20261017");
mkdirSync(out, { recursive: true });
const base = "http://localhost:3107", dashboard = base + "/s/sports-live-flow/admin/dashboard";
let browser;
async function login(context) {
  const page = await context.newPage(); page.setDefaultTimeout(60000);
  await page.goto(base + "/hq/login?store=sports-live-flow");
  await page.getByLabel("Email", { exact: true }).fill("sports-owner@example.invalid");
  await page.getByLabel("密碼", { exact: true }).fill("isolated-sports-test-only");
  await page.getByRole("button", { name: "登入", exact: true }).click();
  await page.waitForURL(dashboard);
  await page.getByRole("heading", { name: "首頁", exact: true }).waitFor();
  return page;
}
try {
  browser = await chromium.launch({ executablePath: process.env.QA_CHROMIUM_EXECUTABLE || "/usr/bin/chromium", headless: true, args: ["--no-sandbox"] });
  const buyerContext = await browser.newContext({ viewport: { width: 1366, height: 900 } });
  const buyer = await login(buyerContext);
  const observerContext = await browser.newContext({ viewport: { width: 1024, height: 768 } });
  const observer = await login(observerContext);
  await observer.goto(dashboard + "/transactions");
  await observer.getByRole("heading", { name: "交易明細", exact: true }).waitFor();
  await observer.evaluate(() => { globalThis.__qaDocumentToken = crypto.randomUUID(); });
  const observerToken = await observer.evaluate(() => globalThis.__qaDocumentToken);
  const before = await course.coursePurchase.count({ where: { storeId: "sports-live-flow-store" } });
  const visibleBefore = await observer.getByRole("button", { name: "查看 運動驗收學員 的 運動驗收十點方案 交易", exact: true }).count();
  await buyer.goto(dashboard + "/courses?view=customers");
  await buyer.getByRole("row").filter({ hasText: "運動驗收學員" }).getByRole("button", { name: "購買方案", exact: true }).click();
  const dialog = buyer.getByRole("dialog");
  await dialog.getByLabel("方案", { exact: true }).selectOption("sports-live-plan");
  await dialog.getByLabel("所屬店長", { exact: true }).selectOption("sports-live-flow-staff");
  await dialog.locator('select[name="paymentMethod"]').selectOption("CARD");
  await dialog.getByRole("button", { name: "確認結帳", exact: true }).click();
  for (let attempt = 0; attempt < 100; attempt++) {
    if (await course.coursePurchase.count({ where: { storeId: "sports-live-flow-store" } }) > before) break;
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  const orders = await course.coursePurchase.findMany({ where: { storeId: "sports-live-flow-store" }, orderBy: { createdAt: "desc" } });
  assert.equal(orders.length, before + 1);
  const order = orders[0];
  assert.equal(order.price, 1000); assert.equal(order.status, "CONFIRMED");
  assert.equal((await course.coursePointCard.findUniqueOrThrow({ where: { id: order.cardId } })).remaining, 10);
  const income = await db.cashbookEntry.findUniqueOrThrow({ where: { id: "course-purchase:" + order.id } });
  assert.equal(Number(income.amount), 1000); assert.equal(income.type, "INCOME");
  console.log("Real purchase committed; observing the idle transaction page for 62 seconds.");
  await new Promise(resolve => setTimeout(resolve, 30_000));
  await new Promise(resolve => setTimeout(resolve, 30_000));
  await new Promise(resolve => setTimeout(resolve, 2_000));
  const visibleAfter = await observer.getByRole("button", { name: "查看 運動驗收學員 的 運動驗收十點方案 交易", exact: true }).count();
  const result = { realLogin: true, realServerAction: true, orderCreatedOnce: true, cardRemaining: 10, income: 1000, observerBefore: visibleBefore, observerAfter: visibleAfter, observerUpdated: visibleAfter === visibleBefore + 1, documentReload: await observer.evaluate(() => globalThis.__qaDocumentToken) !== observerToken };
  await buyer.screenshot({ path: path.join(out, "purchase-customer.png") });
  await observer.screenshot({ path: path.join(out, "observer-transactions.png") });
  writeFileSync(path.join(out, "results.json"), JSON.stringify(result, null, 2));
  if (process.env.QA_REQUIRE_OBSERVER_SYNC === "1") assert.equal(result.observerUpdated, true, "Idle transaction observer did not update");
  const refundedBefore = await observer.getByRole("cell", { name: "已登錄退款", exact: true }).count();
  await buyer.goto(dashboard + "/transactions");
  await buyer.getByRole("button", { name: "查看 運動驗收學員 的 運動驗收十點方案 交易", exact: true }).first().click();
  const detail = buyer.getByRole("dialog");
  await detail.getByRole("button", { name: "登錄退款", exact: true }).click();
  await detail.getByLabel("退款金額（元）", { exact: true }).fill("400");
  await detail.locator("select").selectOption("BANK_TRANSFER");
  await detail.locator("textarea").fill("隔離真實流程驗收退款");
  await detail.getByRole("button", { name: "登錄退款並停用方案", exact: true }).click();
  await detail.getByRole("status").filter({ hasText: "退款已登錄，方案已停用。" }).waitFor();
  const refundedOrder = await course.coursePurchase.findUniqueOrThrow({ where: { id: order.id }, include: { refunds: true } });
  assert.equal(refundedOrder.status, "REFUNDED"); assert.equal(refundedOrder.refunds.length, 1);
  assert.equal(refundedOrder.refunds[0].amount, 400);
  const retired = await course.coursePointCard.findUniqueOrThrow({ where: { id: order.cardId } });
  assert.equal(retired.remaining, 0); assert.ok(retired.closedAt);
  const expense = await db.cashbookEntry.findUniqueOrThrow({ where: { id: "course-refund:" + refundedOrder.refunds[0].id } });
  assert.equal(expense.type, "EXPENSE"); assert.equal(Number(expense.amount), 400);
  console.log("Real refund committed; observing the idle transaction page for 62 seconds.");
  await new Promise(resolve => setTimeout(resolve, 30_000));
  await new Promise(resolve => setTimeout(resolve, 30_000));
  await new Promise(resolve => setTimeout(resolve, 2_000));
  result.refundRecordedOnce = true; result.refundAmount = 400; result.cardRetired = true;
  result.refundObserverUpdated = await observer.getByRole("cell", { name: "已登錄退款", exact: true }).count() === refundedBefore + 1;
  result.documentReload = await observer.evaluate(() => globalThis.__qaDocumentToken) !== observerToken;
  await buyer.screenshot({ path: path.join(out, "refund-detail.png") });
  await observer.screenshot({ path: path.join(out, "observer-refund.png") });
  writeFileSync(path.join(out, "results.json"), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
  if (process.env.QA_REQUIRE_OBSERVER_SYNC === "1") assert.equal(result.refundObserverUpdated, true, "Idle transaction observer did not reflect refund");
  assert.equal(result.documentReload, false);
} finally { await browser?.close(); await db.$disconnect(); await course.$disconnect(); }
